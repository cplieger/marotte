// Command wire-codegen generates static-src/wire/*.gen.ts (the TypeScript interfaces, validating
// decoders, SSE event decoders, property-test arbitraries, the typed client and the WebSocket
// paths) and the OpenAPI document, docs/openapi.json and its embedded copy
// internal/apitable/openapi.json, from the endpoint table and the Go wire types. The contract
// lives in internal/wirespec.
//
// Run: go run ./cmd/wire-codegen   (from the marotte repo root)
package main

import (
	"context"
	"errors"
	"fmt"
	"os"
	"os/signal"
	"path/filepath"
	"strconv"
	"strings"
	"syscall"

	"github.com/cplieger/go/wiregen/v2"
	"github.com/cplieger/marotte/internal/wirespec"
)

const headerComment = "// Code generated by cmd/wire-codegen. DO NOT EDIT.\n\n"

func main() {
	os.Exit(run())
}

// run returns the exit code so the deferred cancel runs on every path. The context is a
// signal context because loading packages runs `go` as a subprocess that can fetch for
// minutes; an interrupt must cancel it so the staged output is cleaned up.
func run() int {
	ctx, stop := signal.NotifyContext(context.Background(), os.Interrupt, syscall.SIGTERM)
	defer stop()

	if err := generate(ctx, "."); err != nil {
		// Name the signal so a cancelled run does not read as a broken registry.
		if errors.Is(err, context.Canceled) {
			fmt.Fprintln(os.Stderr, "wire-codegen: interrupted")
			return 130
		}
		fmt.Fprintf(os.Stderr, "wire-codegen: %v\n", err)
		return 1
	}
	fmt.Println("wire-codegen: generated static-src/wire/*.gen.ts, docs/openapi.json and internal/apitable/openapi.json")
	return 0
}

// generate writes every generated file under root, at the paths the committed tree holds them.
func generate(ctx context.Context, root string) error {
	tsDir := filepath.Join(root, "static-src", "wire")
	err := wirespec.Registry().Generate(ctx,
		wiregen.WithTSDir(tsDir),
		// The property test iterates ARBITRARY_BY_TYPE, so a new wire type needs an arbitrary.
		wiregen.WithArbitrariesFile("arbitraries.gen.ts"),
		wiregen.WithTransportImport("../api-client.js"),
		wiregen.WithHeaderComment(headerComment),
		wiregen.WithOpenAPIFiles(
			filepath.Join(root, "docs", "openapi.json"),
			filepath.Join(root, "internal", "apitable", "openapi.json"),
		),
	)
	if err != nil {
		return err
	}
	return writeSockets(filepath.Join(tsDir, "sockets.gen.ts"))
}

// writeSockets writes the WebSocket entries' paths, which wiregen has no endpoint kind for.
func writeSockets(path string) error {
	var b strings.Builder
	b.WriteString(headerComment)
	sockets := wirespec.Sockets()
	for i := range sockets {
		b.WriteString("export const " + sockets[i].Name + "Path = " + strconv.Quote(sockets[i].Path) + ";\n")
	}
	return os.WriteFile(path, []byte(b.String()), 0o600)
}
