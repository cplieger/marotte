	b.WriteString("its `\"source\":\"apt:<name>\"`, or the engine answers `unknown tool`; progress streams to ")
	b.WriteString("Settings → Tools, and `GET " + serverAddr + "/api/tools/jobs` lists jobs. A catalog install ")
