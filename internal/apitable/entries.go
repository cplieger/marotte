// anyMount is a catch-all mount's seven entries, one per method it answers.
func anyMount(path, summary string, a route.Access) []route.Entry {
	out := make([]route.Entry, 0, len(route.AnyMethods()))
	for _, m := range route.AnyMethods() {
		e := route.Entry{Name: anyName(m, path), Method: m, Path: path, Kind: route.KindRaw, Summary: summary, Access: a, Any: true}
		e.Access.Safe = m == http.MethodGet || m == http.MethodHead
		out = append(out, e)
	}
	return out
}
