package main

import (
	"bytes"
	"fmt"
	"go/format"
	"unicode"
	"unicode/utf16"

	"golang.org/x/text/unicode/norm"
)

// Output paths, relative to the module root.
const (
	goPath = "internal/textsearch/fold_table.go"
	tsPath = "static-src/textsearch/fold-table.gen.ts"
	// genCmd regenerates both files.
	genCmd = "go run ./internal/textsearch/internal/foldgen"
)

// accentPair maps one rune to the base its accents fold to.
type accentPair struct{ From, To rune }

// accentTable lists, in ascending From order, every rune a lowercase fold can produce whose canonical decomposition is
// one base rune followed only by nonspacing marks (Mn), mapped to that base lowercased. A pair whose two runes
// differ in UTF-16 length is left out, so the fold stays length-preserving in both kernels.
func accentTable() []accentPair {
	var out []accentPair
	for r := rune(0x80); r <= unicode.MaxRune; r++ {
		if unicode.Is(unicode.Cs, r) || unicode.ToLower(r) != r {
			continue
		}
		base, ok := accentBase(r)
		if !ok || utf16.RuneLen(base) != utf16.RuneLen(r) {
			continue
		}
		out = append(out, accentPair{From: r, To: base})
	}
	return out
}

func accentBase(r rune) (rune, bool) {
	d := []rune(norm.NFD.String(string(r)))
	if len(d) < 2 || unicode.Is(unicode.M, d[0]) {
		return 0, false
	}
	for _, m := range d[1:] {
		if !unicode.Is(unicode.Mn, m) {
			return 0, false
		}
	}
	return unicode.ToLower(d[0]), true
}

const header = "Code generated by " + genCmd + "; DO NOT EDIT."

// goSource is fold_table.go's content.
func goSource(t []accentPair) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// %s\n\npackage textsearch\n\n", header)
	b.WriteString("// accentFrom and accentTo are parallel: accentFrom[i] folds to accentTo[i]. accentFrom ascends.\n")
	writeGoArray(&b, "accentFrom", t, func(p accentPair) rune { return p.From })
	writeGoArray(&b, "accentTo", t, func(p accentPair) rune { return p.To })
	return format.Source(b.Bytes())
}

func writeGoArray(b *bytes.Buffer, name string, t []accentPair, pick func(accentPair) rune) {
	fmt.Fprintf(b, "var %s = [...]rune{\n", name)
	for i, p := range t {
		fmt.Fprintf(b, "0x%04X,", pick(p))
		if i%12 == 11 {
			b.WriteString("\n")
		}
	}
	b.WriteString("\n}\n\n")
}

// tsSource is fold-table.gen.ts's content.
func tsSource(t []accentPair) []byte {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// %s\n\n", header)
	b.WriteString("/** Parallel arrays: `ACCENT_FROM[i]` folds to `ACCENT_TO[i]`. `ACCENT_FROM` ascends. */\n")
	writeTSArray(&b, "ACCENT_FROM", t, func(p accentPair) rune { return p.From })
	b.WriteString("\n")
	writeTSArray(&b, "ACCENT_TO", t, func(p accentPair) rune { return p.To })
	return b.Bytes()
}

func writeTSArray(b *bytes.Buffer, name string, t []accentPair, pick func(accentPair) rune) {
	fmt.Fprintf(b, "export const %s: readonly number[] = [\n", name)
	for i, p := range t {
		if i%10 == 0 {
			b.WriteString(" ")
		}
		fmt.Fprintf(b, " 0x%04x,", pick(p))
		if i%10 == 9 || i == len(t)-1 {
			b.WriteString("\n")
		}
	}
	b.WriteString("];\n")
}
